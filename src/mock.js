const countMatches = (re, text) => (text.match(re) ?? []).length;

/**
 * Ниша определяется по очкам: совпадения в названии весят втрое больше, чем в описании.
 * Так «Барбершоп» с фразой «можно выпить кофе» остаётся барбершопом, а не кофейней.
 */
export function detectPack(input) {
  const name = input.name.toLowerCase();
  const desc = input.description.toLowerCase();
  let best = null;
  let bestScore = 0;
  for (const pack of PACKS) {
    const score = 3 * countMatches(pack.re, name) + countMatches(pack.re, desc);
    if (score > bestScore) {
      best = pack;
      bestScore = score;
    }
  }
  return best ?? GENERIC;
}

function firstSentences(text, maxChars) {
  const clean = text.replace(/\s+/g, ' ').trim();
  const parts = clean.match(/[^.!?]+[.!?]?/g) ?? [clean];
  let out = '';
  for (const p of parts) {
    if ((out + p).length > maxChars) break;
    out += p;
  }
  return (out || clean.slice(0, maxChars)).trim();
}

